positions = {}

for row in reader:
    symbol = row.get("Instrument", "").strip().upper()
    action = row.get("Trans Code", "").strip().lower()
    qty_str = row.get("Quantity", "").replace(",", "").strip()
    price_str = row.get("Price", "").replace("$", "").replace(",", "").strip()
    desc = row.get("Description", "").strip()
    
    if not symbol or not action:
        continue
        
    try:
        qty = float(qty_str) if qty_str else 0.0
    except ValueError:
        qty = 0.0
        
    try:
        price = float(price_str) if price_str else 0.0
    except ValueError:
        price = 0.0
        
    if symbol not in positions:
        name = desc.split("\n")[0].strip() if desc else symbol
        positions[symbol] = {
            "symbol": symbol,
            "name": name,
            "shares": 0.0,
            "last_price": price,
            "total_bought": 0.0,
            "total_sold": 0.0
        }
        
    if price > 0 and positions[symbol]["last_price"] == 0:
        positions[symbol]["last_price"] = price
        
    if "buy" in action or action == "rec":
        positions[symbol]["shares"] += qty
        positions[symbol]["total_bought"] += qty
    elif "sell" in action:
        positions[symbol]["shares"] -= qty
        positions[symbol]["total_sold"] += qty

print("=== RECONSTRUCTED HOLDINGS FROM ACTIVITY ===")
active_holdings = []
sold_out = []

for sym, data in positions.items():
    shares = round(data["shares"], 6)
    if shares > 0.0001:
        val = round(shares * data["last_price"], 2)
        active_holdings.append((sym, data["name"], shares, data["last_price"], val))
    else:
        sold_out.append((sym, data["name"], shares))

